export type TKey = keyof typeof ar

/** استرجاع نص مترجم مع استبدال {متغير} */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  let s: string = ar[key]
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}
